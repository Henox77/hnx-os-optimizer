        private static void DetectSystemLanguage()
        {
            try
            {
                string sysLang = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLower();
                if (Translations.ContainsKey(sysLang))
                {
                    CurrentLanguage = sysLang;
                }
                else
                {
                    CurrentLanguage = "en"; // Default fallback
                }
            }
            catch
            {
                CurrentLanguage = "en";
            }
        }

        public static string Translate(string key)
        {
            if (string.IsNullOrEmpty(key)) return string.Empty;

            if (Translations.TryGetValue(CurrentLanguage, out var langDict) && langDict.TryGetValue(key, out var val))
            {
                return val;
            }
            // Fallback to English
            if (Translations["en"].TryGetValue(key, out var engVal))
            {
                return engVal;
            }
            return key;
        }

